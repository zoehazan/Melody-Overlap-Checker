"""The Python port must give exactly the same results as the web app's TypeScript.

The expected results come from tests/fixtures/parity.json, generated by the TypeScript code
(cd web && npm run build:py-parity-fixture). If this test fails after a change to web/src,
port the change to melodyfp/ too.
"""
import hashlib
import json
import unittest
from pathlib import Path

from melodyfp.fingerprint import encode, pack_iv, pack_rh, unpack_iv, unpack_rh
from melodyfp.melody import pick_melody, skyline
from melodyfp.midi import Note, parse_midi

from .midi_writer import write_midi

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "parity.json").read_text())


def strip(notes):
    return [[n.pitch, n.start, n.dur] for n in notes]


class ParityWithTypeScript(unittest.TestCase):
    def test_midi_files(self):
        self.assertGreater(len(FIXTURE["files"]), 0)
        for i, case in enumerate(FIXTURE["files"]):
            with self.subTest(file=i):
                data = write_midi(case["spec"])
                self.assertEqual(hashlib.sha256(data).hexdigest(), case["sha256"], "test writer bytes differ")
                parsed = parse_midi(data)
                self.assertEqual([{"name": t.name, "notes": strip(t.notes)} for t in parsed.tracks], case["tracks"])
                self.assertEqual(parsed.beats_per_bar, case["beatsPerBar"])
                pick = pick_melody(parsed) if parsed.tracks else -1
                self.assertEqual(pick, case["pick"])
                sky = skyline(parsed.tracks[pick].notes) if pick >= 0 else []
                self.assertEqual(strip(sky), case["skyline"])
                iv, rh = encode(sky)
                self.assertEqual({"iv": iv, "rh": rh}, case["fp"])

    def test_note_sequences(self):
        for i, case in enumerate(FIXTURE["sequences"]):
            with self.subTest(sequence=i):
                iv, rh = encode([Note(p, s, d) for p, s, d in case["notes"]])
                self.assertEqual({"iv": iv, "rh": rh}, case["fp"])


class PackedText(unittest.TestCase):
    def test_round_trip(self):
        iv = list(range(-12, 13))
        rh = list(range(-3, 4))
        self.assertEqual(pack_iv(iv), "ABCDEFGHIJKLMNOPQRSTUVWXY")
        self.assertEqual(pack_rh(rh), "0123456")
        self.assertEqual(unpack_iv(pack_iv(iv)), iv)
        self.assertEqual(unpack_rh(pack_rh(rh)), rh)



class JavaScriptCompat(unittest.TestCase):
    def test_round_halves_up_like_math_round(self):
        from melodyfp.jsmath import js_round
        self.assertEqual([js_round(x) for x in (0.5, 1.5, 2.5, -0.5, -1.5, -2.4)], [1, 2, 3, 0, -1, -2])

    def test_trim_like_string_trim(self):
        from melodyfp.jsmath import js_trim
        self.assertEqual(js_trim("  Lead\t\n"), "Lead")
        self.assertEqual(js_trim("\x1cLead\x85"), "\x1cLead\x85")  # Python's strip() would remove these


if __name__ == "__main__":
    unittest.main()
